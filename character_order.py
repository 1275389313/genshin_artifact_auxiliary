def is_separator(name):
    '''----风----、----5.8～7.0---- 这类 UI 分隔/占位，不是可玩角色。'''
    text = str(name).strip()
    return text.startswith('----') and text.endswith('----') and len(text) > 8


def is_placeholder(name):
    '''下拉最前的「请选择角色」占位。'''
    return is_separator(name) and '请选择' in str(name)


