RELEASE_DATES = {}
RELEASE_VERSIONS = {}
for _version, _date, _names in _RELEASE_GROUPS:
    for _name in _names:
        RELEASE_DATES[_name] = _date
        RELEASE_VERSIONS[_name] = _version


def sort_character_names(names, newest_first=True):
    '''按上线时间排列下拉项。

    顺序：
      1. 「请选择」占位（保持输入相对顺序）
      2. 通用配装模板（保持输入相对顺序）
      3. 已知角色：默认新→旧；同一天按名称
      4. 未知/用户自定名称：名称升序，稳定排在已知角色之后
      5. 其余 ----分隔----（元素/版本段），仍可选，不参与上线排序
    '''
    seen = set()
    unique = []
    for name in names or ():
        if name in seen:
            continue
        seen.add(name)
        unique.append(name)

    placeholders = []
    separators = []
    presets = []
    known = []
    unknown = []
    for name in unique:
        if is_placeholder(name):
            placeholders.append(name)
        elif is_separator(name):
            separators.append(name)
        elif name in GENERIC_PROFILE_SET:
            presets.append(name)
        elif name in RELEASE_DATES:
            known.append(name)
        else:
            unknown.append(name)

    # 先按名称，再按日期（稳定排序）：同一天名称升序，日期新→旧或旧→新
    known.sort()
    known.sort(key=lambda name: RELEASE_DATES[name], reverse=newest_first)
    unknown.sort()
    return placeholders + presets + known + unknown + separators
